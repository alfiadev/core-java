public class DataSize {
    public static void main(String[] args) {
        System.out.println("size of byte" + Byte.SIZE + " " + "bits");
        System.out.println("size of short" + Short.SIZE + " " + "bits");
        System.out.println("size of long" + Long.SIZE + " " + "bits");
        System.out.println("size of char" + Integer.SIZE + " " + "bits");
        System.out.println("size of short" + Float.SIZE + "  " + "bits");
        System.out.println("size of short" + " " + Double.SIZE + " " + "bits");
        System.out.println("size of short" + Character.SIZE + " " + "bits");
        // System.out.println("size of boolean"+" " + Boolean.SIZE+" " +"bits");
        // The size of boolean is JVM-dependent and not precisely defined.
    }
}
